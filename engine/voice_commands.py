def normalize_persian(text: str) -> str:
    """نرمال‌سازی متن فارسی برای تطبیق فرمان.

    - حذف علائم نگارشی اضافی
    - تبدیل اعداد عربی به فارسی
    - حذف فاصله‌های اضافی
    """
    # اعداد عربی → فارسی
    arabic_digits = "٠١٢٣٤٥٦٧٨٩"
    persian_digits = "۰۱۲۳۴۵۶۷۸۹"
    for a, p in zip(arabic_digits, persian_digits):
        text = text.replace(a, p)

    # حذف علائم نگارشی انتهایی
    text = text.strip(" .؟!؟،؛:«»\"'")

    # حذف فاصله‌های اضافی
    text = re.sub(r"\s+", " ", text).strip()

    return text


def match_command(text: str):
    """تطبیق متن با فهرست فرمان‌ها.

    Returns:
        (matched_pattern, actions) اگر تطبیق پیدا شود، در غیر این صورت None.
    """
    normalized = normalize_persian(text)

    # جمع‌آوری همه الگوها با طول‌شان، به ترتیب نزولی (طولانی‌تر اول)
    all_patterns = []
    for patterns, actions in COMMANDS:
        for pattern in patterns:
            p = pattern.strip()
            if p:
                all_patterns.append((len(p), p, actions))
    all_patterns.sort(key=lambda x: -x[0])

    for _length, p, actions in all_patterns:
        if normalized == p or normalized.endswith(p):
            return p, actions
    return None


def execute_actions(actions):
    """اجرای لیست اکشن‌های کیبورد.

    اکشن‌ها:
        ("press", key_name)    → فشردن و رها کردن یک کلید
        ("combo", "ctrl+a")    → فشردن همزمان چند کلید
        ("type", "text")       → تایپ متن (از طریق clipboard)
    """
    for action in actions:
        kind = action[0]
        if kind == "press":
            keyboard.send(action[1])
        elif kind == "combo":
            keyboard.send(action[1])
        elif kind == "type":
            import pyperclip
            old = ""
            try:
                old = pyperclip.paste()
            except Exception:
                pass
            pyperclip.copy(action[1])
            keyboard.send("ctrl+v")
            try:
                pyperclip.copy(old)
            except Exception:
                pass


def try_execute_voice_command(text: str) -> bool:
    """اگر متن یک فرمان صوتی باشد، آن را اجرا کن و True برگردان."""
    result = match_command(text)
    if result is None:
        return False
    _pattern, actions = result
    execute_actions(actions)
    return True
